"""Site configs of the reverse proxy (deploy/proxy) composed from the enabled components.

Every project writes one YAML file with all its sites into the proxy config directory; the
proxy applies changes without a restart. Routing: each enabled backend gets a route for its
``paths``; ``/`` goes to Next.js when it is enabled, otherwise to ``default_backend`` (whose
paths are then covered by the catch-all). Extra domains send everything to
``default_backend``. Dev sites use the self-signed certificates of dev_balancer.py, production
sites get Let's Encrypt certificates from the proxy itself.
"""
from scripts.compose.services import NEXTJS_PORT, backend_internal_url
from scripts.compose.yaml_dump import dump_yaml
from scripts.constants import project_env
from scripts.deploy_config import BackendName, DeployConfig, get_deploy_config

# Mount point of SSL_CERTS_DIR in the dev proxy container.
DEV_CERTS_MOUNT = '/app/ssl'

# Time to wait for the response headers of the upstream.
_TIMEOUTS: dict[str, str] = {
    'django': '120s',
    'fastapi': '300s',
}

HEADER = '# Generated by deploy (scripts/proxy/configuration.py) for {name}; changes are overwritten.\n'


def _component_url(component: str) -> str:
    if component == 'nextjs':
        return f'http://{project_env.project_name}-nextjs:{NEXTJS_PORT}'
    return backend_internal_url(component)  # type: ignore[arg-type]


def _route(component: str, paths: list[str]) -> dict:
    route: dict = {'paths': paths, 'upstream': _component_url(component)}
    if component in _TIMEOUTS:
        route['timeout'] = _TIMEOUTS[component]
    return route


def _backend_paths(config: DeployConfig, backend: BackendName) -> tuple[str, ...]:
    return config.django.paths if backend == 'django' else config.fastapi.paths


def app_routes(config: DeployConfig) -> list[dict]:
    """Routes of the main domain."""
    catch_all = 'nextjs' if config.nextjs.enabled else config.default_backend
    assert catch_all is not None
    routes = [
        _route(backend, [f'/{path}' for path in _backend_paths(config, backend)])
        for backend in config.backends
        if backend != catch_all
    ]
    routes.append(_route(catch_all, ['/']))
    return routes


def extra_domain_routes(config: DeployConfig) -> list[dict]:
    assert config.default_backend is not None
    return [_route(config.default_backend, ['/'])]


def _dev_tls(cert_name: str) -> dict:
    return {'cert': f'{DEV_CERTS_MOUNT}/{cert_name}.crt', 'key': f'{DEV_CERTS_MOUNT}/{cert_name}.key'}


_ACME_TLS = {'acme': True}


def _app_site(domain: str, tls: dict, routes: list[dict], config: DeployConfig) -> dict:
    return {'domains': [domain], 'tls': tls, 'max_body_size': config.max_body_size, 'routes': routes}


def _centrifugo_site(tls: dict) -> dict:
    name = project_env.project_name
    return {
        'domains': [f'centrifugo.{project_env.project_domain}'],
        'tls': tls,
        'routes': [{'paths': ['/'], 'upstream': f'http://{name}-centrifugo:8000'}],
    }


def _dev_media_site() -> dict:
    """MinIO behind media.<domain>: the S3 API for the media bucket, the console for the rest."""
    name = project_env.project_name
    return {
        'domains': [f'media.{project_env.project_domain}'],
        'tls': _dev_tls(f'media_{name}'),
        'routes': [
            {'paths': [f'/{name}-media'], 'upstream': f'http://{name}-minio:9000'},
            {'paths': ['/'], 'upstream': f'http://{name}-minio:9001'},
        ],
    }


def dev_sites(config: DeployConfig | None = None) -> list[dict]:
    config = config or get_deploy_config()
    name = project_env.project_name
    sites = [_app_site(project_env.project_domain, _dev_tls(name), app_routes(config), config)]
    # The media domain belongs to Django (MinIO behind media.<domain>).
    if config.django.enabled:
        sites.append(_dev_media_site())
    if config.centrifugo_enabled:
        sites.append(_centrifugo_site(_dev_tls(f'centrifugo_{name}')))
    for domain in project_env.extra_domains:
        sites.append(_app_site(domain, _dev_tls(f'{name}_{domain}'), extra_domain_routes(config), config))
    return sites


def prod_sites(config: DeployConfig | None = None) -> list[dict]:
    config = config or get_deploy_config()
    sites = [_app_site(project_env.project_domain, _ACME_TLS, app_routes(config), config)]
    if config.centrifugo_enabled:
        sites.append(_centrifugo_site(_ACME_TLS))
    for domain in project_env.extra_domains:
        sites.append(_app_site(domain, _ACME_TLS, extra_domain_routes(config), config))
    return sites


def site_domains(sites: list[dict]) -> list[str]:
    return [domain for site in sites for domain in site['domains']]


def render_sites(sites: list[dict]) -> str:
    return HEADER.format(name=project_env.project_name) + dump_yaml({'sites': sites})


def config_file_name() -> str:
    return f'{project_env.project_name}.yaml'
