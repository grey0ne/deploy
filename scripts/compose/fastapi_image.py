"""Dockerfiles for the fastapi stack, generated from deploy.json ``fastapi`` settings.

The build context is the project root; a Dockerfile-specific ``.dockerignore`` limits it to the
configured packages so the rest of the repo (spa/node_modules, virtualenvs, data) is never sent.
"""
import json
import os

from scripts.constants import COMPOSE_DIR
from scripts.deploy_config import DeployConfig, FastapiConfig

GENERATED_DIR = os.path.join(COMPOSE_DIR, 'generated')

PYTHON_IMAGE = 'python:3.15.2-slim'
FASTAPI_PORT = 8080

DEV_DOCKERFILE = os.path.join(GENERATED_DIR, 'Dockerfile.fastapidev')
PROD_DOCKERFILE = os.path.join(GENERATED_DIR, 'Dockerfile.fastapiprod')

_IGNORED_IN_PACKAGES = (
    '**/__pycache__',
    '**/*.pyc',
    '**/.pytest_cache',
    '**/.venv',
    '**/.data',
    '**/node_modules',
)


def uvicorn_command(fastapi: FastapiConfig, *, dev: bool, workers: int = 1) -> list[str]:
    command = ['uvicorn', fastapi.app]
    if fastapi.factory:
        command.append('--factory')
    command += ['--host', '0.0.0.0', '--port', str(FASTAPI_PORT)]
    if dev:
        command.append('--reload')
    else:
        command += ['--workers', str(workers)]
    return command


def render_dockerfile(fastapi: FastapiConfig, *, dev: bool) -> str:
    lines = [
        '# Generated by deploy/scripts/compose/fastapi_image.py from deploy.json - do not edit.',
        f'FROM {PYTHON_IMAGE}',
        '',
        'ENV PYTHONUNBUFFERED=1',
        '',
    ]
    if fastapi.apt_packages:
        lines += [
            'RUN apt-get update \\',
            f'    && apt-get install -y --no-install-recommends {" ".join(fastapi.apt_packages)} \\',
            '    && rm -rf /var/lib/apt/lists/*',
            '',
        ]
    lines.append('RUN pip install --upgrade pip --root-user-action=ignore')
    editable = '-e ' if dev else ''
    # One layer per package, in deploy.json order (dependencies first).
    for package in fastapi.packages:
        lines += [
            '',
            f'COPY {package} /deps/{package}',
            f'RUN pip install {editable}/deps/{package} --root-user-action=ignore',
        ]
    lines += [
        '',
        f'WORKDIR /deps/{fastapi.effective_app_dir}',
        f'EXPOSE {FASTAPI_PORT}',
        f'CMD {json.dumps(uvicorn_command(fastapi, dev=dev))}',
        '',
    ]
    return '\n'.join(lines)


def render_dockerignore(fastapi: FastapiConfig) -> str:
    lines = ['# Generated from deploy.json - only fastapi.packages are sent to the build.', '*']
    lines += [f'!{package}' for package in fastapi.packages]
    lines += list(_IGNORED_IN_PACKAGES)
    return '\n'.join(lines) + '\n'


def write_fastapi_dockerfiles(config: DeployConfig) -> None:
    if not config.is_fastapi:
        return
    os.makedirs(GENERATED_DIR, exist_ok=True)
    for path, dev in ((DEV_DOCKERFILE, True), (PROD_DOCKERFILE, False)):
        with open(path, 'w', encoding='utf-8') as f:
            f.write(render_dockerfile(config.fastapi, dev=dev))
        # BuildKit reads <Dockerfile>.dockerignore next to the Dockerfile.
        with open(f'{path}.dockerignore', 'w', encoding='utf-8') as f:
            f.write(render_dockerignore(config.fastapi))
